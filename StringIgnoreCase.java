package StringStarted;

public class StringIgnoreCase {

	public static void main(String[] args) 
	
	{
		
		String s1="HEFSHINE";
		String s2="@#$$%Hefshine";
		
		int ans=s1.compareToIgnoreCase(s2);
		System.out.println(ans);
		
		
		
		//If we have the another case it will be ignored 
		//by comparing to strings 
		//A=69 && a=97
		//
		

	}

}
